//! 传输侧纯计算：固定块几何与流式内容哈希（design §5.4 `crates/transfer/`、§13.1）。
//!
//! 本 crate 被客户端（Windows agent 的上传快照与下载续传）和服务端（接收固定块）共用，因此
//! **不做任何 I/O**：不读文件、不建连接、不碰数据库、不看时钟。这样两端对“块边界”“块摘要”
//! 的判断只能来自同一份代码，续传不会把两份内容拼在一起。
//!
//! - [`chunk`]：一份快照的总大小与块大小决定块数与每块长度（块几何的唯一权威）。
//! - [`hash`]：增量 SHA-256 与摘要比较（整文件流式计算，不把内容整体读进内存）。
//!
//! 续传状态（位图）与传输端口抽象分别属于客户端存储（`crates/client-store`）与服务端端口
//! （`crates/server-core::ports`），本卡不预建空模块。

#![forbid(unsafe_code)]

pub mod chunk;
pub mod hash;
