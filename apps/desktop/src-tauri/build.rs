//! Build Windows resources and deny custom commands unless explicitly permitted.
fn main() {
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        let commands: &'static [&'static str] =
            if std::env::var_os("CARGO_FEATURE_NATIVE_ACCEPTANCE").is_some() {
                &[
                    "agent_list_files",
                    "agent_download_entry",
                    "agent_release_entry",
                    "agent_list_problems",
                    "agent_retry_problem",
                    "agent_set_mode",
                    "agent_get_rules",
                    "agent_set_rules",
                    "agent_detach_binding",
                    "agent_export_recovery",
                    "agent_list_history",
                    "agent_list_trash",
                    "agent_restore_entry",
                    "agent_notification_settings",
                    "agent_set_notifications",
                    "agent_get_status",
                    "agent_set_connection",
                    "agent_login",
                    "agent_logout",
                    "agent_list_vaults",
                    "select_local_directory",
                    "agent_create_binding",
                    "agent_pause_binding",
                    "agent_resume_binding",
                    "acceptance_report",
                    "acceptance_file_control",
                    "acceptance_fixture_phase",
                    "acceptance_toast_history",
                ]
            } else {
                // tauri-build preserves autogenerated files across feature switches.
                // Remove only the test permissions so they cannot enter production ACL metadata.
                for name in [
                    "acceptance_report",
                    "acceptance_file_control",
                    "acceptance_fixture_phase",
                    "acceptance_toast_history",
                ] {
                    match std::fs::remove_file(format!("permissions/autogenerated/{name}.toml")) {
                        Ok(()) => {}
                        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
                        Err(error) => panic!("cannot remove stale test permission: {error}"),
                    }
                }
                &[
                    "agent_list_files",
                    "agent_download_entry",
                    "agent_release_entry",
                    "agent_list_problems",
                    "agent_retry_problem",
                    "agent_set_mode",
                    "agent_get_rules",
                    "agent_set_rules",
                    "agent_detach_binding",
                    "agent_export_recovery",
                    "agent_list_history",
                    "agent_list_trash",
                    "agent_restore_entry",
                    "agent_notification_settings",
                    "agent_set_notifications",
                    "agent_get_status",
                    "agent_set_connection",
                    "agent_login",
                    "agent_logout",
                    "agent_list_vaults",
                    "select_local_directory",
                    "agent_create_binding",
                    "agent_pause_binding",
                    "agent_resume_binding",
                ]
            };
        tauri_build::try_build(
            tauri_build::Attributes::new()
                .app_manifest(tauri_build::AppManifest::new().commands(commands)),
        )
        .expect("valid desktop configuration");
    }
}
