//! Build Windows resources and deny custom commands unless explicitly permitted.
fn main() {
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        let commands: &'static [&'static str] =
            if std::env::var_os("CARGO_FEATURE_NATIVE_ACCEPTANCE").is_some() {
                &[
                    "agent_get_status",
                    "agent_set_connection",
                    "agent_login",
                    "agent_logout",
                    "agent_list_roots",
                    "agent_create_binding",
                    "agent_pause_binding",
                    "agent_resume_binding",
                    "acceptance_report",
                ]
            } else {
                // tauri-build preserves autogenerated files across feature switches.
                // Remove only this test-only permission so it cannot enter production ACL metadata.
                match std::fs::remove_file("permissions/autogenerated/acceptance_report.toml") {
                    Ok(()) => {}
                    Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
                    Err(error) => panic!("cannot remove stale test permission: {error}"),
                }
                &[
                    "agent_get_status",
                    "agent_set_connection",
                    "agent_login",
                    "agent_logout",
                    "agent_list_roots",
                    "agent_create_binding",
                    "agent_pause_binding",
                    "agent_resume_binding",
                ]
            };
        tauri_build::try_build(
            tauri_build::Attributes::new()
                .app_manifest(tauri_build::AppManifest::new().commands(commands)),
        )
        .expect("valid desktop configuration");
    }
}
